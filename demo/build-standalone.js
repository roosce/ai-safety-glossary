#!/usr/bin/env node
/*
 * Build a self-contained, double-click demo: demo/standalone.html
 *
 * The hosted demo (demo/index.html) loads glossary.js and terms.json over
 * http(s). This script bakes those into ONE file that runs straight from the
 * filesystem (file://) with no web server — handy for sharing a preview that
 * someone can just double-click.
 *
 * How it stays faithful to what ships:
 *   - glossary.js is inlined VERBATIM (only the </script> in its header comment
 *     is backslash-escaped, so it can't terminate the surrounding <script> tag;
 *     that's a no-op for the JS, which sees the comment text either way).
 *   - terms.json is embedded and handed to the (unmodified) widget through a
 *     tiny fetch shim, so there's no fetch of any real file.
 *   - Feedback runs in demo mode: submissions are logged to the console, not sent.
 *
 * Re-run after editing glossary.js, terms.json, or demo/index.html:
 *   node demo/build-standalone.js
 */
"use strict";
var fs = require("fs");
var path = require("path");

var dir = __dirname;                 // .../glossary/demo
var root = path.join(dir, "..");     // .../glossary

var demo = fs.readFileSync(path.join(dir, "index.html"), "utf8");
// Escape </script so the inlined widget can't close the <script> tag early.
var js = fs.readFileSync(path.join(root, "glossary.js"), "utf8").replace(/<\/script/gi, "<\\/script");
// Escape </script here too: a term containing that sequence would otherwise
// close the embedded data <script> tag early (broken file + injection risk).
var terms = fs.readFileSync(path.join(root, "terms.json"), "utf8")
  .trim()
  .replace(/<\/script/gi, "<\\/script");

// Take everything up to the hosted demo's <script> tag, then swap that tag for
// the embedded harness + inlined widget.
var marker = '<script src="../glossary.js"';
var cut = demo.indexOf(marker);
if (cut === -1) throw new Error("Couldn't find the widget <script> tag in demo/index.html");
var head = demo.slice(0, cut);

var S = "scr" + "ipt";   // keeps a literal </script> out of THIS source file too
var harness =
  "<!-- GENERATED by demo/build-standalone.js — do not edit by hand.\n" +
  "     glossary.js is inlined verbatim; terms.json is embedded and fed to the\n" +
  "     widget via a fetch shim, so this runs with no server (just double-click).\n" +
  "     Feedback is in demo mode (submissions are logged to the console, not sent). -->\n" +
  "  <" + S + ">\n" +
  "  window.__GLOSSARY_TERMS__ = " + terms + ";\n" +
  "  (function () {\n" +
  "    var realFetch = typeof window.fetch === \"function\" ? window.fetch.bind(window) : null;\n" +
  "    window.fetch = function (url) {\n" +
  "      if (url === \"embedded:terms\") {\n" +
  "        return Promise.resolve({ ok: true, status: 200,\n" +
  "          json: function () { return Promise.resolve(window.__GLOSSARY_TERMS__); } });\n" +
  "      }\n" +
  "      return realFetch ? realFetch.apply(this, arguments)\n" +
  "                       : Promise.reject(new Error(\"fetch unavailable\"));\n" +
  "    };\n" +
  "  })();\n" +
  "  </" + S + ">\n" +
  "  <" + S + " data-terms=\"embedded:terms\" data-root=\"#article\" data-feedback-url=\"demo\">\n" +
  js + "\n" +
  "  </" + S + ">\n" +
  "</body>\n</html>\n";

var out = head + harness;
fs.writeFileSync(path.join(dir, "standalone.html"), out);
console.log("Wrote demo/standalone.html (" + out.length + " bytes, " + terms.length + " bytes of terms)");
